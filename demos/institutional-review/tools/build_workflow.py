def operand(name, source, value):
    src = (f'\n            <sv:property sv:name="source" sv:type="String"><sv:value>{source}</sv:value></sv:property>'
           if source else "")
    return f"""
          <sv:node sv:name="{name}">
            <sv:property sv:name="jcr:primaryType" sv:type="Name"><sv:value>cond:ConditionOperand</sv:value></sv:property>{src}
            <sv:property sv:name="value" sv:type="String" sv:multiple="true"><sv:value>{value}</sv:value></sv:property>
          </sv:node>"""


def guard(source, value, literal):
    return f"""
      <bpmn:extensionElements>
        <sv:node xmlns:sv="http://www.jcp.org/jcr/sv/1.0" sv:name="cond:condition">
          <sv:property sv:name="jcr:primaryType" sv:type="Name"><sv:value>cond:SingleCondition</sv:value></sv:property>
          <sv:property sv:name="comparator" sv:type="String"><sv:value>equals</sv:value></sv:property>{operand("operandA", source, value)}{operand("operandB", None, literal)}
        </sv:node>
      </bpmn:extensionElements>
    """


class Diagram:
    def __init__(self):
        self.shapes = []
        self.edges = []
        self.at = {}

    def shape(self, element, x, y, w, h, marker=False):
        self.at[element] = (x, y, w, h)
        extra = ' isMarkerVisible="true"' if marker else ""
        self.shapes.append(f'      <bpmndi:BPMNShape id="{element}Shape" bpmnElement="{element}"{extra}>\n'
                           f'        <dc:Bounds x="{x}" y="{y}" width="{w}" height="{h}" />\n'
                           f'      </bpmndi:BPMNShape>')

    def edge(self, flow, source, target):
        sx, sy, sw, sh = self.at[source]
        tx, ty, tw, th = self.at[target]
        points = [(sx + sw, sy + sh // 2), (tx, ty + th // 2)]
        if tx <= sx:
            points = [(sx + sw // 2, sy + sh), (sx + sw // 2, sy + sh + 40), (tx + tw // 2, sy + sh + 40),
                      (tx + tw // 2, ty + th)]
        waypoints = "\n".join(f'        <di:waypoint x="{x}" y="{y}" />' for x, y in points)
        self.edges.append(f'      <bpmndi:BPMNEdge id="{flow}Edge" bpmnElement="{flow}">\n{waypoints}\n'
                          f'      </bpmndi:BPMNEdge>')


def build():
    nodes = []
    flows = []
    d = Diagram()
    row = 120

    def flow(fid, source, target, extension=""):
        body = f">{extension}</bpmn:sequenceFlow>" if extension else " />"
        flows.append((fid, source, target, f'    <bpmn:sequenceFlow id="{fid}" sourceRef="{source}" targetRef="{target}"{body}'))

    middle = row * len(REVIEWS) // 2
    nodes.append('    <bpmn:startEvent id="studyStarted" name="Study started" />')
    d.shape("studyStarted", 100, middle, 36, 36)
    nodes.append('    <bpmn:userTask id="fillIn" name="Describe the study" iap:performers="@creator" />')
    d.shape("fillIn", 180, middle - 22, 120, 80)
    flow("toFillIn", "studyStarted", "fillIn")
    nodes.append('    <!-- Sending it is what makes it submitted: a tag step, since only an end event places a host tag -->\n'
                 '    <bpmn:serviceTask id="markSubmitted" name="Send it to the reviewers" iap:handler="addTag"'
                 ' iap:replaceExisting="true" iap:tag="in-review" />')
    d.shape("markSubmitted", 340, middle - 22, 100, 80)
    flow("toMarkSubmitted", "fillIn", "markSubmitted")
    nodes.append('    <bpmn:serviceTask id="prepare" name="Number it for the queue" iap:handler="prepareForReview" />')
    d.shape("prepare", 340, middle + 90, 100, 60)
    flow("toPrepare", "markSubmitted", "prepare")
    nodes.append(f'    <bpmn:serviceTask id="startClock" name="Start the review clock" iap:handler="reviewClock"'
                 f' iap:action="start" iap:duration="{DEADLINE}" iap:fastTrackDuration="{FAST_TRACK_DEADLINE}" />')
    d.shape("startClock", 340, middle + 190, 100, 60)
    flow("toStartClock", "prepare", "startClock")
    nodes.append('    <bpmn:inclusiveGateway id="reviews" name="Who reviews it?" />')
    d.shape("reviews", 480, middle - 7, 50, 50, marker=True)
    flow("toReviews", "startClock", "reviews")
    nodes.append('    <bpmn:inclusiveGateway id="reviewed" name="Reviewed" />')
    d.shape("reviewed", 1380, middle - 7, 50, 50, marker=True)

    for index, (requirement, label, performers, outcomes, guarded) in enumerate(REVIEWS):
        y = 40 + index * row
        task, record = f"{requirement}Task", f"{requirement}Recorded"
        nodes.append(f'    <bpmn:userTask id="{task}" name="{label}" iap:performers="{performers}"'
                     f' iap:outcomeOptions="{outcomes}" />')
        d.shape(task, 620, y, 140, 80)
        # A gateway cannot name a question by its path, so the step numbering the study puts the answers routing it
        # into the run, as variables
        extension = guard("variable", guarded, "true") if guarded else ""
        flow(f"to{task[0].upper()}{task[1:]}", "reviews", task, extension)
        nodes.append(f'    <bpmn:serviceTask id="{record}" name="Write the decision down" iap:handler="recordReview"'
                     f' iap:requirement="{requirement}" />')
        d.shape(record, 820, y, 120, 80)
        flow(f"to{record[0].upper()}{record[1:]}", task, record)
        if requirement != "reb":
            flow(f"{requirement}ToReviewed", record, "reviewed")
            continue
        nodes.append('    <bpmn:exclusiveGateway id="rebDecision" name="REB decision" default="rebApproved" />')
        d.shape("rebDecision", 990, y + 15, 50, 50, marker=True)
        flow("toRebDecision", record, "rebDecision")
        flow("rebApproved", "rebDecision", "reviewed")
        nodes.append('    <bpmn:serviceTask id="markChanges" name="Send it back for changes" iap:handler="addTag"'
                     ' iap:replaceExisting="true" iap:tag="changes-requested" />')
        d.shape("markChanges", 1090, y - 20, 100, 60)
        flow("rebChanges", "rebDecision", "markChanges", guard("variable", "outcome", "changes-requested"))
        nodes.append('    <bpmn:serviceTask id="pauseClock" name="Pause the review clock" iap:handler="reviewClock"'
                     ' iap:action="pause" />')
        d.shape("pauseClock", 1090, y - 110, 100, 60)
        flow("toPauseClock", "markChanges", "pauseClock")
        nodes.append('    <bpmn:userTask id="respond" name="Answer the reviewers" iap:performers="@creator" />')
        d.shape("respond", 1230, y - 20, 120, 60)
        flow("toRespond", "pauseClock", "respond")
        nodes.append('    <bpmn:serviceTask id="markResubmitted" name="Back in review" iap:handler="addTag"'
                     ' iap:replaceExisting="true" iap:tag="in-review" />')
        d.shape("markResubmitted", 1230, y - 110, 120, 60)
        flow("toMarkResubmitted", "respond", "markResubmitted")
        nodes.append('    <bpmn:serviceTask id="resumeClock" name="Resume the review clock" iap:handler="reviewClock"'
                     ' iap:action="resume" />')
        d.shape("resumeClock", 1380, y - 110, 100, 60)
        flow("toResumeClock", "markResubmitted", "resumeClock")
        flow("backToReb", "resumeClock", task)
        nodes.append('    <bpmn:endEvent id="studyRejected" name="Not authorized" iap:hostTag="rejected">\n'
                     '      <bpmn:terminateEventDefinition />\n'
                     '    </bpmn:endEvent>')
        d.shape("studyRejected", 1100, y + 70, 36, 36)
        flow("rebRejected", "rebDecision", "studyRejected", guard("variable", "outcome", "rejected"))

    nodes.append('    <bpmn:endEvent id="studyApproved" name="Authorized" iap:hostTag="approved" />')
    d.shape("studyApproved", 1480, middle, 36, 36)
    flow("toApproved", "reviewed", "studyApproved")

    for fid, source, target, _ in flows:
        d.edge(fid, source, target)

    body = "\n".join(nodes) + "\n" + "\n".join(f[3] for f in flows)
    return (HEADER +
            '<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL"\n'
            '                  xmlns:bpmndi="http://www.omg.org/spec/BPMN/20100524/DI"\n'
            '                  xmlns:dc="http://www.omg.org/spec/DD/20100524/DC"\n'
            '                  xmlns:di="http://www.omg.org/spec/DD/20100524/DI"\n'
            '                  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n'
            '                  xmlns:iap="https://iap.uhndata.io/bpmn"\n'
            '                  id="retrospectiveStudyDefinitions"\n'
            '                  targetNamespace="https://iap.uhndata.io/workflows/retrospectiveStudy">\n'
            '  <bpmn:process id="retrospectiveStudy" name="Retrospective data study" isExecutable="true">\n'
            f"{body}\n"
            "  </bpmn:process>\n"
            '  <bpmndi:BPMNDiagram id="retrospectiveStudyDiagram">\n'
            '    <bpmndi:BPMNPlane id="retrospectiveStudyPlane" bpmnElement="retrospectiveStudy">\n'
            + "\n".join(d.shapes) + "\n" + "\n".join(d.edges) + "\n"
            "    </bpmndi:BPMNPlane>\n"
            "  </bpmndi:BPMNDiagram>\n"
            "</bpmn:definitions>\n")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print(f"{len(REVIEWS)} reviews")
